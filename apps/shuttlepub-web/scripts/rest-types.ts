import { join } from "node:path";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";
import { EMUMET_PIN, OPENAPI_DIR, SHUTTLEPUB_PIN, verifyLock, type OpenApiPin } from "../bff/openapi/lock.ts";

export const REST_TYPES_RELATIVE_PATH = "bff/rest/generated/shuttlepub-api.ts";
export const EMUMET_TYPES_RELATIVE_PATH = "bff/rest/generated/emumet-api.ts";

/**
 * The Emumet OpenAPI tags whose operations this app consumes: Profile-scoped
 * domain controls, individual blocks/mutes and follow lists (personal-domain-controls-web-ui).
 */
export const EMUMET_CONSUMED_TAGS = ["ProfilePolicy"] as const;

/** Every generated REST type file, the pin it is rendered from and the tags it covers (all when absent). */
export const REST_TYPE_TARGETS: readonly { path: string; pin: OpenApiPin; tags?: readonly string[] }[] = [
  { path: REST_TYPES_RELATIVE_PATH, pin: SHUTTLEPUB_PIN },
  { path: EMUMET_TYPES_RELATIVE_PATH, pin: EMUMET_PIN, tags: EMUMET_CONSUMED_TAGS },
];

type Json = Record<string, unknown>;

function collectRefs(node: unknown, refs: Set<string>): void {
  if (Array.isArray(node)) {
    for (const item of node) collectRefs(item, refs);
  } else if (typeof node === "object" && node !== null) {
    for (const [key, value] of Object.entries(node)) {
      if (key === "$ref" && typeof value === "string") refs.add(value);
      else collectRefs(value, refs);
    }
  }
}

/**
 * The vendored document is verbatim from the producer and is the contract of record. The
 * generated types only cover the operations this app calls (`tags`) plus the schemas they
 * reference, which keeps the generated file reviewable. It also avoids openapi-typescript's
 * `operationId must be unique` validation, which the Emumet document currently fails
 * (get_followers / get_following are each declared twice). Same approach as apps/emumet-web.
 */
export function subsetForTags(document: OpenAPI3, tags: readonly string[]): OpenAPI3 {
  const source = document as unknown as Json & { paths: Record<string, Record<string, Json>>; components: { schemas: Record<string, Json> } };
  const paths: Record<string, Record<string, Json>> = {};
  for (const [path, item] of Object.entries(source.paths)) {
    const operations = Object.values(item);
    if (operations.length > 0 && operations.every((operation) => Array.isArray(operation["tags"]) && (operation["tags"] as string[]).some((tag) => tags.includes(tag)))) {
      paths[path] = item;
    }
  }
  const needed = new Set<string>();
  const refs = new Set<string>();
  collectRefs(paths, refs);
  const pending = [...refs];
  while (pending.length > 0) {
    const ref = pending.pop() as string;
    const match = /^#\/components\/schemas\/(.+)$/.exec(ref);
    if (!match || needed.has(match[1] as string)) continue;
    needed.add(match[1] as string);
    const next = new Set<string>();
    collectRefs(source.components.schemas[match[1] as string], next);
    pending.push(...next);
  }
  const schemas: Record<string, Json> = {};
  for (const name of [...needed].sort()) schemas[name] = source.components.schemas[name] as Json;
  const subset = {
    openapi: source["openapi"],
    info: source["info"],
    paths,
    components: { schemas, securitySchemes: source.components["securitySchemes" as keyof typeof source.components] },
  };
  return subset as unknown as OpenAPI3;
}

/**
 * Full text of a generated REST type file for its pinned schema (ShuttlePub by default).
 * Verifies the producer pin first, so a tampered schema never produces types.
 */
export async function renderRestTypes(pin: OpenApiPin = SHUTTLEPUB_PIN, tags?: readonly string[]): Promise<string> {
  const lock = await verifyLock(OPENAPI_DIR, pin);
  const document = JSON.parse(await Bun.file(join(OPENAPI_DIR, pin.schemaFile)).text()) as OpenAPI3;
  const ast = await openapiTS(tags === undefined ? document : subsetForTags(document, tags));
  const header = [
    "/**",
    ` * Generated by scripts/codegen.ts (openapi-typescript) from openapi/${pin.schemaFile}.`,
    ...(tags === undefined ? [] : [` * Covers only the operations tagged ${tags.join(", ")} and the schemas they reference.`]),
    ` * Producer: ${lock.producer.repository}@${lock.producer.commit}`,
    ` * Schema sha256: ${lock.schema.sha256}`,
    " * Do not edit by hand: run `bun run codegen`.",
    " */",
    "",
  ].join("\n");
  return `${header}${astToString(ast)}`;
}
